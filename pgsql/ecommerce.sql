-- ------------------------------------------------ sequence resync
-- Seed rows insert explicit ids (GENERATED BY DEFAULT allows this); move
-- each identity sequence past the seeded maximum.

SELECT setval(pg_get_serial_sequence('users',            'user_id'),     (SELECT coalesce(max(user_id),     0) + 1 FROM users),            false);
SELECT setval(pg_get_serial_sequence('addresses',        'address_id'),  (SELECT coalesce(max(address_id),  0) + 1 FROM addresses),        false);
SELECT setval(pg_get_serial_sequence('categories',       'category_id'), (SELECT coalesce(max(category_id), 0) + 1 FROM categories),       false);
SELECT setval(pg_get_serial_sequence('products',         'product_id'),  (SELECT coalesce(max(product_id),  0) + 1 FROM products),         false);
SELECT setval(pg_get_serial_sequence('product_variants', 'variant_id'),  (SELECT coalesce(max(variant_id),  0) + 1 FROM product_variants), false);
SELECT setval(pg_get_serial_sequence('product_images',   'image_id'),    (SELECT coalesce(max(image_id),    0) + 1 FROM product_images),   false);
SELECT setval(pg_get_serial_sequence('carriers',         'carrier_id'),  (SELECT coalesce(max(carrier_id),  0) + 1 FROM carriers),         false);
SELECT setval(pg_get_serial_sequence('carts',            'cart_id'),     (SELECT coalesce(max(cart_id),     0) + 1 FROM carts),            false);
SELECT setval(pg_get_serial_sequence('orders',           'order_id'),    (SELECT coalesce(max(order_id),    0) + 1 FROM orders),           false);

COMMIT;
